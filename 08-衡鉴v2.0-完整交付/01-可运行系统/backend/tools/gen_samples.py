def _iter_lines(spec: dict) -> list[tuple[str, bool]]:
    """把 sections 摊平成 (文本, 是否新页) 序列。"""
    out: list[tuple[str, bool]] = []
    every = spec.get("page_break_every") or 0
    for idx, (title, paras) in enumerate(spec["sections"]):
        newpage = bool(every and idx > 0 and idx % every == 0)
        out.append((title, newpage))
        for p in paras:
            out.append((p, False))
    return out


def make_docx(spec: dict, path: Path) -> None:
    from docx import Document
    from docx.enum.text import WD_BREAK
    from docx.shared import Pt

    doc = Document()
    style = doc.styles["Normal"]
    style.font.name = "Microsoft YaHei"
    style.font.size = Pt(10.5)

    # 标题
    head = doc.add_heading(spec["name"], level=0)
    for run in head.runs:
        run.font.name = "Microsoft YaHei"

    for text, newpage in _iter_lines(spec):
        p = doc.add_paragraph()
        if newpage:
            p.add_run().add_break(WD_BREAK.PAGE)
        p.add_run(text)
    doc.save(str(path))


def make_pdf(spec: dict, path: Path, *, password: str | None = None) -> None:
    import fitz
    doc = fitz.open()
    page = doc.new_page(width=595, height=842)
    y = 60.0
    left = 52.0
    bottom = 790.0

    def wrap(text: str, width: int = 44) -> list[str]:
        lines, line = [], ""
        for ch in text:
            line += ch
            if len(line) >= width:
                lines.append(line)
                line = ""
        if line:
            lines.append(line)
        return lines

    def put(text: str, size: float = 10.5, gap: float = 17.0):
        nonlocal page, y
        for seg in wrap(text, int(48 * 10.5 / size)):
            if y > bottom:
                page = doc.new_page(width=595, height=842)
                y = 60.0
            page.insert_text((left, y), seg, fontsize=size, fontname="china-s")
            y += gap

    put(spec["name"], size=15, gap=26)
    y += 6
    for text, _newpage in _iter_lines(spec):
        put(text)
    y += 10
    put("（本合同为示例文本，仅供系统演示与评测使用）", size=9)

    if password:
        doc.save(str(path), encryption=fitz.PDF_ENCRYPT_AES_256, owner_pw=password,
                 user_pw=password, deflate=True)
    else:
        doc.save(str(path), deflate=True)
    doc.close()


def _load_font(size: int):
    from PIL import ImageFont
    for cand in FONT_CANDIDATES:
        p = Path(cand)
        if p.exists():
            try:
                return ImageFont.truetype(str(p), size, index=0)
            except Exception:
                try:
                    return ImageFont.truetype(str(p), size)
                except Exception:
                    continue
    return ImageFont.load_default()


def make_scan(spec: dict, path: Path) -> None:
    """把合同渲染成"扫描件"：白底黑字 + 轻微倾斜/噪点/边缘阴影，模拟真实复印件。"""
    import random

    from PIL import Image, ImageDraw, ImageFilter

    width, height = 1654, 2339          # A4 @200dpi
    img = Image.new("RGB", (width, height), (250, 249, 246))
    draw = ImageDraw.Draw(img)
    font_title = _load_font(34)
    font_body = _load_font(26)

    lines: list[str] = [spec["name"]]
    for text, _np in _iter_lines(spec):
        lines.extend(_wrap_cn(text, 40))

    y = 150
    for i, line in enumerate(lines):
        if y > height - 160:
            break
        draw.text((140, y), line, fill=(28, 28, 32),
                  font=font_title if i == 0 else font_body)
        y += 52 if i == 0 else 42
        if i == 0:
            y += 18

    # 扫描噪声
    rnd = random.Random(20260919)
    px = img.load()
    for _ in range(int(width * height * 0.0016)):
        x, yy = rnd.randrange(width), rnd.randrange(height)
        v = rnd.randint(200, 242)
        px[x, yy] = (v, v, v)
    img = img.filter(ImageFilter.GaussianBlur(0.4))
    img = img.rotate(-0.35, expand=False, fillcolor=(250, 249, 246))
    draw = ImageDraw.Draw(img)
    for x in range(width):                       # 右侧装订阴影
        if x > width - 70:
            draw.line([(x, 0), (x, height)], fill=(228, 226, 220))
    img.save(str(path))


def _wrap_cn(text: str, width: int) -> list[str]:
    out, line = [], ""
    for ch in text:
        line += ch
        if len(line) >= width:
            out.append(line)
            line = ""
    if line:
        out.append(line)
    return out


